def _parse(block: str, tipo: str, ley: str) -> dict:
    out = {}
    for line in block.strip().splitlines():
        p = [x.strip() for x in line.split("|")]
        if len(p) < 14:
            continue
        out[p[0]] = {
            "ticker": p[0], "emision": p[1], "vto": p[2], "frec": _FREQ[p[3]],
            "tasa": float(p[4]), "accr": float(p[5]), "vr": float(p[6]),
            "cuotas": int(p[7]), "cierre_ars": float(p[8]), "paridad": float(p[9]),
            "vt": float(p[10]), "ytm": float(p[11]), "dm": float(p[12]),
            "wal": float(p[13]), "tipo": tipo, "ley": ley,
            "bullet": int(p[7]) == 1,
        }
    return out


